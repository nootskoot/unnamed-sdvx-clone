def load(path):
    data = {}
    with open(path, newline="") as fh:
        for row in csv.reader(fh):
            if len(row) != 5 or row[0] == "build":
                continue
            build, section, case, metric, value = row
            try:
                data[(build, section, case, metric)] = float(value)
            except ValueError:
                data[(build, section, case, metric)] = value
    return data


def git(*args):
    try:
        return subprocess.check_output(["git", "-C", REPO] + list(args), text=True).strip()
    except Exception:
        return "unavailable"


def sha(path):
    try:
        with open(path, "rb") as fh:
            return hashlib.sha1(fh.read()).hexdigest()[:12]
    except Exception:
        return "absent"


BEFORE = load(os.path.join(BUILD, "before.csv"))
AFTER = load(os.path.join(BUILD, "after.csv"))


def val(build, section, case, metric):
    v = (BEFORE if build == "before" else AFTER).get((build, section, case, metric))
    return v


def num(build, section, case, metric, digits=0):
    v = val(build, section, case, metric)
    if v is None:
        return "missing"
    if isinstance(v, str):
        return v
    if digits == 0:
        return f"{v:.0f}"
    return f"{v:.{digits}f}"


def delta_after_before(section, case, metric, digits=2, invert=False):
    b = val("before", section, case, metric)
    a = val("after", section, case, metric)
    if b is None or a is None:
        return "missing"
    d = b - a if invert else a - b
    return f"{d:+.{digits}f}"


